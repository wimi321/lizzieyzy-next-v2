#!/usr/bin/env python3
"""Convert Java translation bundles to a sorted, reference-only JSON library.

Run from any directory. --check compares generated bytes without writing files.
The default bundle is English; regional bundles keep their own BCP 47 tags.
"""

import argparse
import json
from pathlib import Path
import re
import sys
from typing import Iterator, Optional


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SOURCE = ROOT.parent / "lizzieyzy-next/src/main/resources/l10n"
DEFAULT_OUTPUT = ROOT / "apps/desktop/src/locales/legacy"
WHITESPACE = " \t\f"


def logical_lines(text: str) -> Iterator[tuple[int, str]]:
    """Join odd-backslash continuations, retaining value trailing whitespace."""
    pending = ""
    continuing = False
    start = 1
    physical_lines = re.split(r"\r\n|\r|\n", text)
    if physical_lines[-1] == "":
        physical_lines.pop()  # A final line terminator does not create a new line.
    for number, physical in enumerate(physical_lines, 1):
        line = physical.lstrip(WHITESPACE)
        if not pending:
            if not line or line[0] in "#!":
                continuing = False
                continue
        if not continuing:
            start = number
        line = pending + line
        backslashes = len(line) - len(line.rstrip("\\"))
        if backslashes % 2:
            pending = line[:-1]
            continuing = True
        else:
            yield start, line
            pending = ""
            continuing = False
    if continuing:
        # Like Properties.load, a final unpaired backslash is discarded at EOF.
        yield start, pending


def unescape(text: str) -> str:
    """Decode Properties escapes (not Python, JSON or MessageFormat escapes)."""
    result = []
    index = 0
    escapes = {"t": "\t", "n": "\n", "r": "\r", "f": "\f"}
    while index < len(text):
        char = text[index]
        index += 1
        if char == "\\":
            if index == len(text):
                raise ValueError("incomplete backslash escape")
            char = text[index]
            index += 1
            if char == "u":
                digits = text[index : index + 4]
                if len(digits) != 4 or any(c not in "0123456789abcdefABCDEF" for c in digits):
                    raise ValueError("invalid Unicode escape (expected \\uXXXX)")
                char = chr(int(digits, 16))
                index += 4
            else:
                # For other escaped characters Java removes only the backslash.
                char = escapes.get(char, char)
        result.append(char)
    # Java strings use UTF-16: combine paired escapes without rejecting unpaired
    # surrogates, which JSON can represent using their original Unicode escapes.
    return "".join(result).encode("utf-16-le", "surrogatepass").decode(
        "utf-16-le", "surrogatepass"
    )


def parse_properties(text: str) -> dict[str, str]:
    """Read raw bundle entries; repeated keys use the last value, as in Java."""
    properties = {}
    for number, line in logical_lines(text):
        key_end = 0
        while key_end < len(line):
            char = line[key_end]
            if char in "=:" + WHITESPACE:
                break
            key_end += 2 if char == "\\" else 1
        value_start = key_end
        while value_start < len(line) and line[value_start] in WHITESPACE:
            value_start += 1
        if value_start < len(line) and line[value_start] in "=:":
            value_start += 1
        while value_start < len(line) and line[value_start] in WHITESPACE:
            value_start += 1
        try:
            properties[unescape(line[:key_end])] = unescape(line[value_start:])
        except ValueError as error:
            raise ValueError("line {}: {}".format(number, error)) from error
    return properties


def language_tag(path: Path) -> str:
    """Convert the locale suffix used by these Java bundles to BCP 47 casing."""
    suffix = path.stem.removeprefix("DisplayStrings")
    if not suffix:
        return "en"
    if not re.fullmatch(r"_[A-Za-z]{2,8}(?:_[A-Za-z0-9]{2,8})*", suffix):
        raise ValueError("unsupported bundle locale: {}".format(path.name))
    parts = suffix[1:].split("_")
    result = [parts[0].lower()]
    for part in parts[1:]:
        if len(part) == 4 and part.isalpha():
            result.append(part.title())
        elif len(part) == 2 and part.isalpha():
            result.append(part.upper())
        elif (len(part) == 3 and part.isdigit()) or (
            5 <= len(part) <= 8 or (len(part) == 4 and part[0].isdigit())
        ):
            result.append(part.lower())
        else:
            raise ValueError("unsupported bundle locale: {}".format(path.name))
    return "-".join(result)


def convert(source_dir: Path) -> dict[str, tuple[Path, dict[str, str], bytes]]:
    sources = sorted(source_dir.glob("DisplayStrings*.properties"))
    if not sources:
        raise ValueError("no DisplayStrings*.properties files in {}".format(source_dir))
    bundles = {}
    for source in sources:
        tag = language_tag(source)
        if tag in bundles:
            raise ValueError("multiple bundles map to {}.json".format(tag))
        raw = source.read_bytes()
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            # PropertyResourceBundle on Java 9+ tries UTF-8, then ISO-8859-1.
            text = raw.decode("iso-8859-1")
        try:
            entries = parse_properties(text)
        except ValueError as error:
            raise ValueError("{}: {}".format(source, error)) from error
        rendered = json.dumps(entries, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
        bundles[tag + ".json"] = (
            source,
            entries,
            rendered.encode("utf-8", "backslashreplace"),
        )
    return bundles


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="compare only; do not write")
    args = parser.parse_args(argv)
    try:
        bundles = convert(args.source_dir)
        if args.check:
            problems = []
            actual = {path.name for path in args.output_dir.glob("*.json")}
            for name in sorted(actual - bundles.keys()):
                problems.append("unexpected file: {}".format(name))
            for name, (_, _, expected) in bundles.items():
                path = args.output_dir / name
                if not path.is_file():
                    problems.append("missing file: {}".format(name))
                elif path.read_bytes() != expected:
                    problems.append("out of date: {}".format(name))
            if problems:
                for problem in problems:
                    print("convert-l10n: " + problem, file=sys.stderr)
                return 1
        else:
            args.output_dir.mkdir(parents=True, exist_ok=True)
            for name, (_, _, rendered) in bundles.items():
                (args.output_dir / name).write_bytes(rendered)
        for name, (source, entries, _) in bundles.items():
            print("{} -> {}: {} keys".format(source.name, name, len(entries)))
        print("convert-l10n: {}".format("check passed" if args.check else "converted"))
        return 0
    except (OSError, ValueError) as error:
        print("convert-l10n: {}".format(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
