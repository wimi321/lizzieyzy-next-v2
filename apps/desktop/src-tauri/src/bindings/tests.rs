#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

use ts_rs::TS;

use super::export;

fn files(directory: &Path) -> BTreeMap<String, Vec<u8>> {
    fs::read_dir(directory)
        .unwrap()
        .map(|entry| {
            let entry = entry.unwrap();
            assert!(entry.file_type().unwrap().is_file());
            (
                entry.file_name().into_string().unwrap(),
                fs::read(entry.path()).unwrap(),
            )
        })
        .collect()
}

fn differences(left: &Path, right: &Path) -> BTreeSet<String> {
    let left = files(left);
    let right = files(right);
    left.keys()
        .chain(right.keys())
        .filter(|name| left.get(*name) != right.get(*name))
        .cloned()
        .collect()
}

#[test]
fn generated_bindings_are_current() {
    let generated = tempfile::tempdir().unwrap();
    export(generated.path()).unwrap();
    let checked_in = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/api/generated");
    let different = differences(generated.path(), &checked_in);
    assert!(
        different.is_empty(),
        "Rust IPC types changed in {different:?}; run cargo run -p lizzieyzy-desktop --bin export-bindings"
    );
}

#[test]
fn dto_field_change_is_detected_without_regeneration() {
    // A changed DTO uses the same exported name as the original. Both sides
    // are generated by ts-rs; this exercises schema drift without source scans.
    #[derive(TS)]
    #[ts(rename = "Revision")]
    struct ChangedRevision {
        #[ts(type = "number")]
        value: u64,
    }

    let original = tempfile::tempdir().unwrap();
    let changed = tempfile::tempdir().unwrap();
    export(original.path()).unwrap();
    export(changed.path()).unwrap();
    fs::write(
        changed.path().join("Revision.ts"),
        ChangedRevision::export_to_string().unwrap(),
    )
    .unwrap();
    let dto = ChangedRevision { value: 7 };
    assert_eq!(dto.value, 7);
    assert_eq!(
        differences(original.path(), changed.path()),
        BTreeSet::from(["Revision.ts".into()])
    );
}
